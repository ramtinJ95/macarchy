  }

  private func readThemeConfiguration() throws -> String {
    let data: Data
    do {
      data = try BoundedRegularFile.read(at: themeConfigurationURL).data
    } catch BoundedRegularFileError.tooLarge {
      throw YaziAdapterError.configurationTooLarge(themeConfigurationURL)
    } catch {
      throw YaziAdapterError.cannotReadConfiguration(themeConfigurationURL)
    }
    guard let configuration = String(data: data, encoding: .utf8) else {
      throw YaziAdapterError.cannotReadConfiguration(themeConfigurationURL)
    }
    return configuration
  }

  private static func selectsFlavor(in configuration: String) -> Bool {
    var inFlavor = false
    var selections = [String]()
    for rawLine in configuration.split(separator: "\n") {
      let line =
        rawLine.split(separator: "#", maxSplits: 1).first?.trimmingCharacters(
          in: .whitespaces) ?? ""
      if line.hasPrefix("[") {
        inFlavor = line == "[flavor]"
      } else if inFlavor {
        let parts = line.split(separator: "=", maxSplits: 1).map {
          $0.trimmingCharacters(in: .whitespaces)
        }
        if parts.first == "dark" {
          selections.append(parts.count == 2 ? parts[1] : "")
        }
      }
    }
    return selections == ["\"\(flavorName)\""]
  }

  private static func isIntegrationDrift(_ error: any Error) -> Bool {
    switch error {
    case is CanonicalThemeLinkError, YaziAdapterError.missingFlavorSelection:
      true
    default:
      false
    }
  }
}
