import Foundation

enum YaziAdapterError: Error, CustomStringConvertible, Sendable {
  case cannotReadConfiguration(URL)
  case configurationTooLarge(URL)
  case controlUnavailable(URL)
  case missingFlavorSelection(String)

  var description: String {
    switch self {
    case .cannotReadConfiguration(let url):
      "Cannot read Yazi theme configuration at \(url.path)"
    case .configurationTooLarge(let url):
      "Yazi theme configuration at \(url.path) exceeds 1 MiB"
    case .controlUnavailable(let url):
      "Yazi control is not executable at \(url.path)"
    case .missingFlavorSelection(let selection):
      "Yazi theme configuration must select \(selection)"
    }
  }
}

struct YaziAdapter: Sendable {
  static let id = "yazi"
  static let flavorOutputPath = "generated/yazi-flavor.toml"
  static let syntaxOutputPath = "generated/yazi.tmTheme"
  static let rendererVersion = 1
  static let flavorName = "macarchy-current"
  static let liveExecutableURL = URL(filePath: "/opt/homebrew/bin/yazi")
  static let liveControlURL = URL(filePath: "/opt/homebrew/bin/ya")

  private static let killallURL = URL(filePath: "/usr/bin/killall")

  let root: URL
  let configurationDirectoryURL: URL
  let executableURL: URL
  let controlURL: URL
  let controlsAreAvailable: @Sendable () -> Bool
  let processRunner: ProcessRunner

  private var themeConfigurationURL: URL {
    configurationDirectoryURL.appending(path: "theme.toml")
  }

  private var flavorDirectoryURL: URL {
    configurationDirectoryURL.appending(
      path: "flavors/\(Self.flavorName).yazi", directoryHint: .isDirectory)
  }

  private var flavorLink: CanonicalThemeLink {
    CanonicalThemeLink(
      url: flavorDirectoryURL.appending(path: "flavor.toml"),
      destination: root.appending(path: "current/\(Self.flavorOutputPath)")
    )
  }

  private var syntaxLink: CanonicalThemeLink {
    CanonicalThemeLink(
      url: flavorDirectoryURL.appending(path: "tmtheme.xml"),
      destination: root.appending(path: "current/\(Self.syntaxOutputPath)")
    )
  }

  func preflight() throws {
    guard controlsAreAvailable() else {
      throw YaziAdapterError.controlUnavailable(
        FileManager.default.isExecutableFile(atPath: executableURL.path)
          ? controlURL : executableURL
      )
    }
    try flavorLink.validate()
    try syntaxLink.validate()

    let configuration = try readThemeConfiguration()
    guard Self.selectsFlavor(in: configuration) else {
      throw YaziAdapterError.missingFlavorSelection(
        "[flavor] dark = \"\(Self.flavorName)\""
      )
    }
  }

  func inspection() -> AdapterInspection {
    do {
      try preflight()
      return AdapterInspection(
        adapterID: Self.id,
        requirement: .required,
        message: "Yazi uses the generated flavor and supports live theme reload"
      )
    } catch {
      return AdapterInspection(
        adapterID: Self.id,
        requirement: .required,
        status: Self.isIntegrationDrift(error) ? .drifted : .failed,
        message: String(describing: error)
      )
    }
  }

  func reconciliation() -> AdapterReconciliation {
    AdapterReconciliation(id: Self.id, requirement: .required) {
      do {
        try preflight()
      } catch {
        return AdapterOutcome(
          status: Self.isIntegrationDrift(error) ? .drifted : .failed,
          message: String(describing: error)
        )
      }

      let running = try processRunner.run(
        ProcessRequest(executableURL: Self.killallURL, arguments: ["-0", "yazi"])
      )
      guard running.terminationStatus == 0 else {
        return AdapterOutcome(
          status: .applied,
          message: "Yazi will use the active palette on next launch"
        )
      }

      let reload = try processRunner.run(
        ProcessRequest(
          executableURL: controlURL,
          arguments: ["emit-to", "0", "theme"],
          timeout: 1
        )
      )
      if reload.terminationStatus == 0 {
        return AdapterOutcome(status: .applied, message: "Running Yazi sessions reloaded")
      }

      let stillRunning = try processRunner.run(
        ProcessRequest(executableURL: Self.killallURL, arguments: ["-0", "yazi"])
      )
      guard stillRunning.terminationStatus == 0 else {
        return AdapterOutcome(
          status: .applied,
          message: "Yazi will use the active palette on next launch"
        )
      }
      return AdapterOutcome(
        status: .failed,
        message: reload.output.isEmpty ? "Yazi rejected its theme reload action" : reload.output
      )
    }
  }

