import Foundation

enum EzaAdapterError: Error, CustomStringConvertible, Sendable {
  case cannotReadShellConfiguration(URL)
  case configurationTooLarge(URL)
  case controlUnavailable(URL)
  case missingEnvironmentDirective(String)

  var description: String {
    switch self {
    case .cannotReadShellConfiguration(let url):
      "Cannot read shell configuration at \(url.path)"
    case .configurationTooLarge(let url):
      "Shell configuration at \(url.path) exceeds 1 MiB"
    case .controlUnavailable(let url):
      "eza is not executable at \(url.path)"
    case .missingEnvironmentDirective(let directive):
      "Shell configuration must contain '\(directive)'"
    }
  }
}

struct EzaAdapter: Sendable {
  static let id = "eza"
  static let outputPath = "generated/eza.yml"
  static let rendererVersion = 1
  static let liveExecutableURL = URL(filePath: "/opt/homebrew/bin/eza")

  let root: URL
  let configurationDirectoryURL: URL
  let shellConfigurationURL: URL
  let executableURL: URL
  let controlIsAvailable: @Sendable () -> Bool
  let processRunner: ProcessRunner

  private var themeLink: CanonicalThemeLink {
    CanonicalThemeLink(
      url: configurationDirectoryURL.appending(path: "theme.yml"),
      destination: root.appending(path: "current/\(Self.outputPath)")
    )
  }

  private var environmentDirective: String {
    "export EZA_CONFIG_DIR=\"\(configurationDirectoryURL.path)\""
  }

  func preflight() throws {
    guard controlIsAvailable() else {
      throw EzaAdapterError.controlUnavailable(executableURL)
    }
    try themeLink.validate()

    let shell = try readShellConfiguration()
    guard Self.containsLine(environmentDirective, in: shell) else {
      throw EzaAdapterError.missingEnvironmentDirective(environmentDirective)
    }
  }

  func inspection() -> AdapterInspection {
    do {
      try preflight()
      return AdapterInspection(
        adapterID: Self.id,
        requirement: .required,
        message: "Fresh eza invocations read the canonical palette"
      )
    } catch {
      return AdapterInspection(
        adapterID: Self.id,
        requirement: .required,
        status: Self.isIntegrationDrift(error) ? .drifted : .failed,
        message: String(describing: error)
      )
    }
  }

  func reconciliation() -> AdapterReconciliation {
    AdapterReconciliation(id: Self.id, requirement: .required) {
      do {
        try preflight()
      } catch {
        return AdapterOutcome(
          status: Self.isIntegrationDrift(error) ? .drifted : .failed,
          message: String(describing: error)
        )
      }

      let result = try processRunner.run(
        ProcessRequest(
          executableURL: executableURL,
          arguments: ["--color=always", "--oneline", themeLink.url.path],
          timeout: 1,
          environmentOverrides: ["EZA_CONFIG_DIR": configurationDirectoryURL.path]
        )
      )
      guard result.terminationStatus == 0 else {
        return AdapterOutcome(
          status: .failed,
          message: result.output.isEmpty ? "eza rejected the active palette" : result.output
        )
      }
      return AdapterOutcome(
        status: .applied,
        message: "Fresh eza invocations use the active palette"
      )
    }
  }

